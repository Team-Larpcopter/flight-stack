#!/usr/bin/env python3
"""OAK-D S2 calibration -> sqrtVINS / OpenVINS Kalibr-format configs.

    oak_to_kalibr.py CALIB.json OUT_DIR [--imu-hz 200]

CALIB.json (see dump_oak_calib.py) holds, for the 1280x800 left/right images:
  left/right: {"K": 3x3, "D": rational_polynomial [k1,k2,p1,p2,k3,k4,k5,k6], "size": [w,h]}
  T_parent_left / T_parent_right / T_parent_imu: 4x4 from TF (metres)

sqrtVINS only supports pinhole-radtan and equidistant lens models; the OAK lens
needs the 8-coefficient rational model (a radtan fit is ~2 px mean / 24 px max
off, printed for reference). So the images are undistorted on the camera
(larp_oak /oak/*/image_undistorted) and the config describes a pinhole camera
with zero distortion and the same K.

Writes OUT_DIR/kalibr_imucam_chain.yaml and kalibr_imu_chain.yaml (the
estimator settings live in the hand-maintained estimator_config.yaml).

Axes: T_cam_imu (Kalibr convention: maps IMU-frame points into the camera
frame) = inv(T_parent_cam) @ T_parent_imu, from the TF larp_oak publishes. The
IMU frame is the BNO086 RAW axes; larp_oak places it with the device's factory
IMU->camera extrinsics, so no axis flip is added here.
"""

import argparse
import json
import os

import numpy as np


def rational_distort(x, y, d):
    k1, k2, p1, p2, k3, k4, k5, k6 = d
    r2 = x * x + y * y
    radial = (1 + k1 * r2 + k2 * r2**2 + k3 * r2**3) / (1 + k4 * r2 + k5 * r2**2 + k6 * r2**3)
    xd = x * radial + 2 * p1 * x * y + p2 * (r2 + 2 * x * x)
    yd = y * radial + p1 * (r2 + 2 * y * y) + 2 * p2 * x * y
    return xd, yd


def undistort_points(u, v, K, d, iters=20):
    """Pixel -> normalised undistorted ray by fixed-point iteration (OpenCV-style)."""
    xd = (u - K[0][2]) / K[0][0]
    yd = (v - K[1][2]) / K[1][1]
    x, y = xd.copy(), yd.copy()
    for _ in range(iters):
        xr, yr = rational_distort(x, y, d)
        x, y = x - (xr - xd), y - (yr - yd)
    return x, y


def fit_radtan(K, d, size, step=8):
    w, h = size
    u, v = np.meshgrid(np.arange(0, w, step, dtype=float), np.arange(0, h, step, dtype=float))
    u, v = u.ravel(), v.ravel()
    x, y = undistort_points(u, v, K, d)
    xd, yd = rational_distort(x, y, d)
    r2 = x * x + y * y
    # radtan: xd = x(1 + k1 r2 + k2 r4) + 2 p1 x y + p2 (r2 + 2x^2), same for y: linear in params
    ax = np.stack([x * r2, x * r2 * r2, 2 * x * y, r2 + 2 * x * x], 1)
    ay = np.stack([y * r2, y * r2 * r2, r2 + 2 * y * y, 2 * x * y], 1)
    A = np.vstack([ax, ay])
    b = np.concatenate([xd - x, yd - y])
    coef, *_ = np.linalg.lstsq(A, b, rcond=None)
    pred = A @ coef
    err_norm = np.hypot((pred - b)[: len(x)], (pred - b)[len(x) :])
    err_px = err_norm * K[0][0]
    return [float(c) for c in coef], {
        "max_px": round(float(err_px.max()), 3),
        "p95_px": round(float(np.percentile(err_px, 95)), 3),
        "mean_px": round(float(err_px.mean()), 3),
    }


def mat_lines(m, indent="    "):
    return "\n".join(f"{indent}- [{', '.join(f'{v:.9f}' for v in row)}]" for row in m)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("calib")
    ap.add_argument("out")
    ap.add_argument("--imu-hz", type=float, default=200.0)
    ap.add_argument("--imu-topic", default="/oak/imu/data")
    a = ap.parse_args()
    c = json.load(open(a.calib))
    os.makedirs(a.out, exist_ok=True)
    T_pi = np.array(c["T_parent_imu"])
    report, cams = {}, []
    for i, side in enumerate(("left", "right")):
        cam = c[side]
        K, d, size = np.array(cam["K"]), cam["D"], cam["size"]
        radtan, err = fit_radtan(K, d, size)
        report[side] = {"radtan": radtan, "fit_error": err}
        # undistorted upstream with the full rational model: pinhole, zero distortion
        radtan, topic = [0.0, 0.0, 0.0, 0.0], f"/oak/{side}/image_undistorted"
        T_pc = np.array(c[f"T_parent_{side}"])
        T_cam_imu = np.linalg.inv(T_pc) @ T_pi  # maps IMU-frame points into this camera
        cams.append(
            f"""cam{i}:
  T_cam_imu:
{mat_lines(T_cam_imu)}
  cam_overlaps: [{1 - i}]
  camera_model: pinhole
  distortion_coeffs: [{', '.join(f'{v:.9f}' for v in radtan)}]
  distortion_model: radtan
  intrinsics: [{K[0][0]:.6f}, {K[1][1]:.6f}, {K[0][2]:.6f}, {K[1][2]:.6f}]
  resolution: [{size[0]}, {size[1]}]
  rostopic: {topic}
  timeshift_cam_imu: 0.0
"""
        )
    open(os.path.join(a.out, "kalibr_imucam_chain.yaml"), "w").write(
        "%YAML:1.0\n# Generated by oak_to_kalibr.py from the OAK-D S2 factory calibration.\n"
        + "# Lens: undistorted on the camera (larp_oak), so pinhole with zero distortion.\n\n"
        + "\n".join(cams)
    )
    # BNO086 noise: starting values (cuVSLAM's in skybeta, inflated x2 white / x10 walk as
    # OpenVINS recommends). Replace with an Allan-variance calibration if time allows.
    open(os.path.join(a.out, "kalibr_imu_chain.yaml"), "w").write(f"""%YAML:1.0
# Generated by oak_to_kalibr.py. BNO086 on the OAK-D S2; noise values are starting guesses.
imu0:
  T_i_b:
{mat_lines(np.eye(4))}
  accelerometer_noise_density: {0.001862 * 2:.9f}
  accelerometer_random_walk: {0.003 * 10:.9f}
  gyroscope_noise_density: {0.000244 * 2:.9f}
  gyroscope_random_walk: {0.000019393 * 10:.9f}
  rostopic: {a.imu_topic}
  time_offset: 0.0
  update_rate: {a.imu_hz}
  model: "kalibr"
  Tw:
{mat_lines(np.eye(3))}
  R_IMUtoGYRO:
{mat_lines(np.eye(3))}
  Ta:
{mat_lines(np.eye(3))}
  R_IMUtoACC:
{mat_lines(np.eye(3))}
  Tg:
{mat_lines(np.zeros((3, 3)))}
""")
    print("radtan fit error (reference only, not used):", json.dumps({s: report[s]["fit_error"] for s in report}))


if __name__ == "__main__":
    main()
